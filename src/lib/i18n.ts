// «4 года» / «4 жыл» — со склонением по-русски
export function yearsLabel(years: number, lang: Lang): string {
  if (lang === "kk") return `${years} жыл`;
  const m = years % 100, d = years % 10;
  const word = m >= 11 && m <= 14 ? "лет" : d === 1 ? "год" : d >= 2 && d <= 4 ? "года" : "лет";
  return `${years} ${word}`;
}

// «стаж 4 года» / «тәжірибе 4 жыл»
export function expLabel(years: number, lang: Lang): string {
  return (lang === "kk" ? "тәжірибе " : "стаж ") + yearsLabel(years, lang);
}

// Перевод пользовательского текста «о себе»: сначала целиком, затем по предложениям
export function tText(text: string, lang: Lang): string {
  if (lang !== "kk" || !text) return text;
  if (KK[text]) return KK[text];
  return text
    .split(/(?<=\.)\s+/)
    .map((s) => KK[s] ?? s)
    .join(" ");
}

export function makeT(lang: Lang) {
  return (s: string) => (lang === "kk" ? KK[s] ?? s : s);
}

// Название профессии с учётом языка (label_kk из БД)
export function profName(p: { label: string; label_kk?: string | null } | undefined | null, lang: Lang): string {
  if (!p) return "";
  return lang === "kk" && p.label_kk ? p.label_kk : p.label;
}

// «от 150 000 ₸» / «150 000 ₸-ден» / «Договорная» / «Келісімді»
export function priceLabelL(price: number | null, lang: Lang): string {
  if (!price) return lang === "kk" ? "Келісімді" : "Договорная";
  const n = price.toLocaleString("ru-RU");
  return lang === "kk" ? `${n} ₸-ден` : `от ${n} ₸`;
}
